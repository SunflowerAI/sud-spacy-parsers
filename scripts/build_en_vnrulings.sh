#!/usr/bin/env bash
# Rebuild the EWT+GUM base corpus under the 2026-10-26 comp:obl / mod rulings, train the base parser on it and
# score it on its own test split. Everything is derived from files in this repo, and nothing under assets/ is
# modified: the copies live in assets_en_vnr_$TAG/ and corpus_en_gum_$TAG/.
#
#   bash scripts/build_en_vnrulings.sh [TAG]          # default TAG=vnrulings
#
# Input: assets/en_ewtgum-sud-<split>.relabeled_ext[.udep_ruled].conllu, read and copied, never written. The rulings
# are decided from scratch from VerbNet, so running them over the installed files gives the same labels as over the
# pre-ruling generation except for tokens that keep their current label (`novn`), which the first pass already fixed.
# The lexicon is rebuilt first (scripts/build_en_vnrulings_lexicon.py; Wiktionary dumps in ../lexicons) and the
# relabelling is pointed at that copy via --lexicon. The `.udep_ruled`
# files are generated by the existing pipeline and are not tracked in git.
set -euo pipefail
cd "$(dirname "$0")/.."
TAG=${1:-vnrulings}
PY=.venv/bin/python
SRC=assets_en_$TAG; COR=corpus_en_gum_$TAG; OUT=training_en_gum_$TAG
rm -rf "$SRC" "$COR" "$OUT"; mkdir -p "$SRC" "$COR" metrics/en_gum
for s in train dev test; do
  for v in relabeled_ext relabeled_ext.udep_ruled; do
    cp "assets/en_ewtgum-sud-$s.$v.conllu" "$SRC/"
  done
done
A=$SRC/en_ewtgum-sud
$PY scripts/build_en_vnrulings_lexicon.py --out "$SRC/en_vnrulings_lexicon.json" > "$SRC/lexicon.log" 2>&1
$PY scripts/relabel_vnrulings.py --lexicon "$SRC/en_vnrulings_lexicon.json" --inplace "$A"-*.relabeled_ext.conllu "$A"-*.udep_ruled.conllu > "$SRC/relabel.log"
for s in train dev test; do
  $PY scripts/resolve_udep.py "$A-$s.relabeled_ext.conllu" --ruled "$A-$s.relabeled_ext.udep_ruled.conllu" \
    --table-from "$A-train.relabeled_ext.conllu" "$A-train.relabeled_ext.udep_ruled.conllu" \
    --out "$A-$s.relabeled_ext.udep_resolved.conllu" > /dev/null
  $PY -m spacy convert "$A-$s.relabeled_ext.udep_resolved.conllu" "$COR/" --converter conllu -n 10 > /dev/null 2>&1
done
C=$COR/en_ewtgum-sud
PYTHONUNBUFFERED=1 $PY -u -m spacy train configs/config.cfg --output "$OUT/" \
  --paths.train "$C-train.relabeled_ext.udep_resolved.spacy" --paths.dev "$C-dev.relabeled_ext.udep_resolved.spacy" \
  > "train_en_gum_$TAG.log" 2>&1
$PY -m spacy evaluate "$OUT/model-best" "$C-test.relabeled_ext.udep_resolved.spacy" \
  --output "metrics/en_gum/metrics_en_gum_$TAG.json" > "eval_$TAG.log" 2>&1
echo DONE
