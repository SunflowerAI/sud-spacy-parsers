class IdLemmaCaseFix:
    def __init__(self, nlp, name):
        pass

    def __call__(self, doc):
        for tok in doc:
            text = tok.text
            if len(text) < 2 or not text[0].isupper() or text[1:] != text[1:].lower():
                continue
            if tok.lemma_ != text:
                continue
            lemma = ID_HYPHEN_LEMMA_LUT.get(text.lower())
            if lemma:
                tok.lemma_ = lemma
        return doc

@Language.factory("id_lemma_case_fix")
def make_id_lemma_case_fix(nlp, name):
    return IdLemmaCaseFix(nlp, name)
